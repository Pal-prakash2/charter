const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const ts = require("typescript");
const file = path.resolve(__dirname, "../lib/waiting-policy.ts");
const loaded = new Module(file, module);
loaded._compile(ts.transpileModule(fs.readFileSync(file,"utf8"), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText, file);
const { conservativeWaiting, withWaitingPolicy } = loaded.exports;
const gate = (status) => ({id:"review",title:"Provider review",status,reason:"Evidence incomplete",sourceIds:[]});
const absent = {label:"None documented (editorial estimate)",basis:"editorial",detail:"No review duration was found.",sourceIds:[]};
const original = JSON.parse(JSON.stringify(absent));
const uncertain = conservativeWaiting(absent, [gate("unknown")]);
assert.equal(uncertain.basis,"unknown");
assert.equal(uncertain.label,"End-to-end wait not established");
assert.ok(uncertain.detail.includes("Provider review"));
console.log("PASS Missing review evidence does not imply zero external waiting");
const published={label:"Five business days",basis:"provider",detail:"Applies to the first review stage only.",sourceIds:["s1"]};
const partial=conservativeWaiting(published,[gate("unknown")]);
assert.equal(partial.basis,"unknown");assert.ok(partial.detail.includes("Five business days"));assert.deepEqual(partial.sourceIds,["s1"]);
console.log("PASS A known stage estimate is preserved without promising the overall wait");
assert.deepEqual(conservativeWaiting(published,[gate("required")]),published);
console.log("PASS Resolved gates retain their supported estimate");
assert.deepEqual(conservativeWaiting(uncertain,[gate("unknown")]),uncertain);
console.log("PASS Policy is idempotent");
assert.deepEqual(absent,original);
console.log("PASS Source estimate is not mutated");
assert.deepEqual(conservativeWaiting(absent,[]),absent);
console.log("PASS Policy does not invent gates");
const snapshot={id:"saved",origin:"generated",version:"2026-10-21.1",researchStatus:"partial",waiting:absent,gates:[gate("unknown")],context:{audience:"external",capability:"read",stage:"launching"}};
const revision=withWaitingPolicy(snapshot);
assert.equal(revision.version,"2026-10-21.1.wait-policy1");assert.equal(revision.waiting.basis,"unknown");assert.deepEqual(revision.context,snapshot.context);assert.equal(snapshot.waiting.label,absent.label);
assert.deepEqual(withWaitingPolicy(revision),revision);
console.log("PASS Historical snapshots receive an explicit, stable policy revision without being rewritten");
assert.equal(withWaitingPolicy({...snapshot,origin:"reviewed"}).waiting,absent);
console.log("PASS Editorial evidence is not silently reinterpreted");
